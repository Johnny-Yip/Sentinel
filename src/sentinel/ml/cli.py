"""Command-line entry point for Sentinel V3 baseline training."""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

import pandas as pd

from sentinel.ml.data import MLError, load_dataset
from sentinel.ml.models import DEFAULT_RANDOM_STATE
from sentinel.ml.reporting import print_model_report, print_split_report
from sentinel.ml.splitting import chronological_split
from sentinel.ml.training import save_artifacts, train_baselines


def default_output_dir(feature_csv: str | Path) -> Path:
    """Return artifacts/<dataset-name> for a V2 feature CSV."""
    stem = Path(feature_csv).stem.removesuffix("_features")
    return Path("artifacts") / stem


def _non_negative_integer(value: str) -> int:
    parsed = int(value)
    if parsed < 0:
        raise argparse.ArgumentTypeError("must be non-negative")
    return parsed


def add_temporal_options(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--dataset-metadata", type=Path,
                        help="Feature metadata sidecar or repository-to-sidecar manifest (default: adjacent sidecars)")
    parser.add_argument("--validation-start", help="UTC validation-start day; explicit and shared for prospective LOPO")
    parser.add_argument("--test-start", help="UTC test-start day; labels used for selection must mature strictly before it")
    parser.add_argument("--test-end", help="Last test snapshot day (default: common observation end minus 90 days)")


def temporal_options(args: argparse.Namespace) -> dict[str, str | None]:
    return {name: getattr(args, name) for name in ("validation_start", "test_start", "test_end")}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Train and evaluate leakage-safe Sentinel V3 baselines on a V2 CSV."
        )
    )
    parser.add_argument("feature_csv", type=Path, help="CSV generated by sentinel-features")
    add_temporal_options(parser)
    parser.add_argument(
        "--output-dir",
        type=Path,
        help="Artifact directory (default: artifacts/<dataset-name>)",
    )
    parser.add_argument(
        "--random-state",
        type=_non_negative_integer,
        default=DEFAULT_RANDOM_STATE,
        help=f"Deterministic model seed (default: {DEFAULT_RANDOM_STATE})",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    output_dir = args.output_dir or default_output_dir(args.feature_csv)

    try:
        print(f"Loading and validating {args.feature_csv}...")
        data = load_dataset(args.feature_csv, dataset_metadata=args.dataset_metadata)
        print(f"Validated {len(data):,} snapshots with 8 historical predictors.")
        splits = chronological_split(data, **temporal_options(args))
        result = train_baselines(
            splits,
            random_state=args.random_state,
            progress=print,
        )
        print_split_report(splits)
        print_model_report(result)
        print(
            "\nLeakage audit: PASS (date-grouped chronological split; train-only "
            "preprocessing; validation-only selection; final-only test use; "
            "historical feature whitelist; verified provenance and 90-day label maturity)."
        )
        print(f"Temporal protocol: {result.temporal_audit['protocol']}; retained rows: "
              f"{result.temporal_audit['retained_rows']}; excluded rows: {result.temporal_audit['excluded_rows']}")
        model_path, metadata_path = save_artifacts(result, output_dir)
    except (
        MLError,
        OSError,
        UnicodeError,
        pd.errors.ParserError,
        ValueError,
    ) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    print(f"\nModel artifact: {model_path}")
    print(f"Metadata artifact: {metadata_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
